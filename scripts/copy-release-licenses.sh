#!/bin/sh
set -eu
JOURNAL_ROOT=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)
JOURNAL_DEST=${1:?usage: copy-release-licenses.sh OUTPUT_DIRECTORY}
JOURNAL_GO=${JOURNAL_GO:-go}
JOURNAL_GOROOT=$("$JOURNAL_GO" env GOROOT)
mkdir -p "$JOURNAL_DEST"
cp "$JOURNAL_ROOT/LICENSE" "$JOURNAL_DEST/LICENSE"
cp "$JOURNAL_ROOT/THIRD_PARTY_NOTICES.md" "$JOURNAL_DEST/THIRD_PARTY_NOTICES.md"
cp "$JOURNAL_GOROOT/LICENSE" "$JOURNAL_DEST/Go-LICENSE.txt"
if [ -f "$JOURNAL_GOROOT/PATENTS" ]; then cp "$JOURNAL_GOROOT/PATENTS" "$JOURNAL_DEST/Go-PATENTS.txt"; fi
